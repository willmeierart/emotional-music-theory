import { FUNCTION_LABEL, relativeOf, type Chord } from '../theory/chords'
import { isRaisedMinorV } from '../theory/feeling'
import { explainChord } from '../theory/explain'
import { isExperimental, type EvaluatedMove, type ScaleMap } from '../theory/map'
import type { Selection } from './selection'

type Props = {
  map: ScaleMap
  selection: Selection
  onNode: (degree: number) => void
}

const FEELING_TAG = { his: 'This key', relative: 'Same chords' } as const

function noteList(chords: Chord[], names: string[]): string {
  return chords
    .map((c) => c.notes.map((pc) => names[pc] ?? '?').join('·'))
    .join('  ')
}

function ChordBlock({ chord, names }: { chord: Chord; names: string[] }) {
  return (
    <div className="chord-block">
      <div className="chord-symbol">{chord.symbol}</div>
      <div className="chord-meta">
        <span>{chord.roman}</span>
        {chord.fn ? <span className="fn">{FUNCTION_LABEL[chord.fn]}</span> : null}
      </div>
      <div className="tones">{chord.notes.map((pc) => names[pc] ?? '?').join(' · ')}</div>
    </div>
  )
}

const SOURCE_TAG: Record<EvaluatedMove['source'], string> = {
  poster: 'Exact',
  relative: 'Same chords',
  extrapolated: 'Extrapolated',
}

function CounterpartNote({ edge }: { edge: EvaluatedMove }) {
  const c = edge.counterpart!
  const move = `${c.fromRoman}→${c.toRoman} (${c.fromSymbol}→${c.toSymbol})`
  if (edge.source === 'poster') {
    return (
      <p className="counterpart">
        {c.sameDegrees
          ? `Same qualities, functions, and leading-tone situation as ${move}.`
          : `Same situation as ${move}, “${c.label}”.`}
      </p>
    )
  }
  return (
    <div className="counterpart">
      <p>
        In C major, {move} is “{c.label}”. What differs here:
      </p>
      <ul>
        {c.differences.map((d) => (
          <li key={d}>{d}</li>
        ))}
      </ul>
    </div>
  )
}

export function Inspector({ map, selection, onNode }: Props) {
  if (selection.kind === 'none') {
    const incomplete = map.cycles.filter((c) => !c.complete && map.chords.length > 1)
    return (
      <aside className="inspector">
        <h2>{map.rootName} {map.scale.name}</h2>
        {isExperimental(map.scale.id) ? (
          <p className="warn experimental">
            Experimental: most moves here are generated by rules fitted to his C-major map, not taken from it. Treat
            these labels as guesses.
          </p>
        ) : null}
        <p className="lede">
          {map.chords.length} degrees. Click a node to hear its triad, or an arrow to hear the move.
        </p>
        <p className="coverage">
          <strong>
            {map.posterCount} of {map.edges.length}
          </strong>{' '}
          moves match the C-major map, so they keep their labels.
          {map.relativeCount > 0 ? (
            <>
              {' '}
              <strong>{map.relativeCount}</strong>
              {map.posterCount > 0 ? ' more' : ''} are the same two chords in the relative
              major, where his reading carries over.
            </>
          ) : null}{' '}
          The rest are <em>extrapolated</em>: inferred from those reasons, shown next to the closest matching move.
        </p>
        <ol className="degree-list">
          {map.chords.map((c) => {
            const feeling = map.feelings[c.degree]
            return (
              <li key={c.degree}>
                <strong>{c.symbol}</strong>
                <span>{c.roman}</span>
                {feeling ? <em>{feeling.label}</em> : c.fn ? <em>{FUNCTION_LABEL[c.fn]}</em> : null}
              </li>
            )
          })}
        </ol>
        {incomplete.length > 0 ? (
          <p className="warn">
            {incomplete.map((c) => `${c.kind} only visit ${c.visited} of ${c.total}`).join(' · ')}
            . The loop is the orbit that contains the tonic.
          </p>
        ) : null}
        {map.chords.some((c) => isRaisedMinorV(c, map.tonicPc, map.chords[0]!.quality)) ? (
          <p className="note">
            He says a minor key keeps the same relationships, except the V chord, whose nature changes a little by
            becoming major.
          </p>
        ) : null}
        {map.scale.inferred ? (
          <p className="note">Interval formula for this scale is a standard-theory stand-in.</p>
        ) : null}
      </aside>
    )
  }

  if (selection.kind === 'node') {
    const chord = map.chords[selection.degree]
    if (!chord) return null
    const feeling = map.feelings[chord.degree]
    const relative = relativeOf(map.chords, chord)
    const relativeFeeling = relative ? map.feelings[relative.degree] : null
    return (
      <aside className="inspector">
        <p className="kicker">Chord</p>
        {feeling ? (
          <>
            <p className={`source source-${feeling.source === 'his' ? 'poster' : 'relative'}`}>
              {FEELING_TAG[feeling.source]}
            </p>
            <h2>{feeling.label}</h2>
          </>
        ) : null}
        <ChordBlock chord={chord} names={map.names} />
        {feeling ? (
          <>
            <p className="lede">{feeling.reason}</p>
            {feeling.note ? <p className="aside">{feeling.note}</p> : null}
          </>
        ) : (
          <p className="aside">No label for this chord: it isn’t one the map covers in this key.</p>
        )}
        <p className="kicker">In the notes</p>
        <p className="theory">{feeling?.theory ?? explainChord(chord, map.chords[0]!, map.names)}</p>
        {relative ? (
          <p className="lever">
            Try its relative,{' '}
            <button
              type="button"
              onClick={(e) => {
                e.stopPropagation()
                onNode(relative.degree)
              }}
            >
              {relative.symbol}
            </button>
            , to shade it {chord.quality === 'maj' ? 'darker' : 'brighter'}
            {relativeFeeling ? ` (${relativeFeeling.label})` : ''}.
          </p>
        ) : null}
      </aside>
    )
  }

  const edge: EvaluatedMove | undefined = map.edges.find((e) => e.id === selection.edgeId)
  if (!edge) return null

  return (
    <aside className="inspector">
      <p className="kicker">{edge.kind} · {edge.structural}</p>
      <p className={`source source-${edge.source}`}>{SOURCE_TAG[edge.source]}</p>
      <h2>{edge.label}</h2>
      {edge.source === 'relative' && edge.relative ? (
        <p className="counterpart">{edge.relative.note}</p>
      ) : edge.counterpart && !edge.relative ? (
        <CounterpartNote edge={edge} />
      ) : null}
      <p className="lede">{edge.because}</p>
      {edge.source === 'extrapolated' && edge.relative ? (
        <p className="aside">{edge.relative.note}</p>
      ) : null}
      <p className="kicker">In the notes</p>
      <p className="theory">{edge.theory}</p>
      <div className="pair">
        <ChordBlock chord={edge.from} names={map.names} />
        <span className="arrow">→</span>
        <ChordBlock chord={edge.to} names={map.names} />
      </div>
      <p className="tones">
        Shared {edge.sharedNames.length ? edge.sharedNames.join(' · ') : 'none'}
      </p>
      <p className="sr-only">{noteList([edge.from, edge.to], map.names)}</p>
    </aside>
  )
}
